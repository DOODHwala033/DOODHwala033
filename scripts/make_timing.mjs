// Usage: node scripts/make_timing.mjs <script.txt> <captions.json> <out timing.ts> [fps]
// Maps each script line (one shot per line) to the start time of its first
// word in a Caption[] file, and writes cut points for the composition.
import fs from "node:fs";

const [scriptPath, capsPath, outPath, fpsArg] = process.argv.slice(2);
const fps = Number(fpsArg ?? 30);
const norm = (w) => w.toLowerCase().replace(/[^a-z0-9'-]/g, "");
const lines = fs.readFileSync(scriptPath, "utf8").split("\n").map((l) => l.trim()).filter(Boolean);
const caps = JSON.parse(fs.readFileSync(capsPath, "utf8"));
const words = caps.map((c) => ({ w: norm(c.text), s: c.startMs / 1000, e: c.endMs / 1000 })).filter((x) => x.w);

let i = 0;
const starts = [];
for (const line of lines) {
  const n = line.split(/\s+/).map(norm).filter(Boolean).length;
  if (i >= words.length) throw new Error(`ran out of words at line: ${line}`);
  starts.push(words[i].s);
  i += n;
}
if (i !== words.length) console.warn(`warning: script has ${i} words, captions have ${words.length}`);
const end = words[words.length - 1].e + 0.6;
const out = `// Generated by scripts/make_timing.mjs from ${capsPath}. Do not edit by hand.
export const FPS = ${fps};
export const LINE_STARTS = ${JSON.stringify(starts.map((s) => Math.round(s * 100) / 100))};
export const DURATION = ${Math.round(end * fps)};
// cut 3 frames before each line so the picture leads the voice
export const CUTS = [...LINE_STARTS.map((s, i) => (i === 0 ? 0 : Math.round(s * FPS) - 3)), DURATION];
`;
fs.writeFileSync(outPath, out);
console.log(`${lines.length} shots, ${end.toFixed(2)}s → ${outPath}`);
