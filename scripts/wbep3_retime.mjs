// Re-time Wheel Battle Ep3 to the real voiceover.
// Usage: node scripts/wbep3_retime.mjs <aligned_captions.json>
// The captions must be the VO words aligned to public/wbep3/script.txt (one
// line per shot; use scripts/align_captions.mjs on the Whisper output first).
// Writes src/WheelBattleEp3/timing.ts: each shot starts at its line's first
// word (cut 3 frames early); the end card starts 0.6 s after the last word.
import fs from "node:fs";

const [capsPath] = process.argv.slice(2);
const fps = 30;
const norm = (w) => w.toLowerCase().replace(/[^a-z0-9'-]/g, "");
const lines = fs.readFileSync("public/wbep3/script.txt", "utf8").split("\n").map((l) => l.trim()).filter(Boolean);
const caps = JSON.parse(fs.readFileSync(capsPath, "utf8"));
const words = caps.map((c) => ({ w: norm(c.text), s: c.startMs / 1000, e: c.endMs / 1000 })).filter((x) => x.w);
let i = 0;
const starts = [];
for (const line of lines) {
  const n = line.split(/\s+/).map(norm).filter(Boolean).length;
  if (i >= words.length) throw new Error(`ran out of words at line: ${line}`);
  starts.push(Math.round(words[i].s * 100) / 100);
  i += n;
}
if (i !== words.length) console.warn(`warning: script has ${i} words, captions have ${words.length}`);
starts[0] = 0;
const endAt = Math.round((words[words.length - 1].e + 0.6) * 100) / 100;
const out = `// Generated by scripts/wbep3_retime.mjs from ${capsPath}. Do not edit by hand.
export const FPS = ${fps};
export const LINE_STARTS = ${JSON.stringify(starts)};
// 6.7 end card (no VO)
export const END_AT = ${endAt};
export const DURATION = ${Math.round((endAt + 2.1) * fps)};
// cut 3 frames before each line so the picture leads the voice
export const CUTS = [
  ...LINE_STARTS.map((s, i) => (i === 0 ? 0 : Math.round(s * FPS) - 3)),
  Math.round(END_AT * FPS) - 3,
  DURATION,
];
`;
fs.writeFileSync("src/WheelBattleEp3/timing.ts", out);
console.log(`${lines.length} shots, end card at ${endAt}s`);
