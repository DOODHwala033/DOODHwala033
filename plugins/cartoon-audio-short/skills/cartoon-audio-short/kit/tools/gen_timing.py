#!/usr/bin/env python3
"""work/phrases.json + work/words.json -> web/timing.js (frames @30). Re-run after a new voiceover."""
import json, re, math
P = json.load(open('work/phrases.json')); W = json.load(open('work/words.json'))
TOTAL = P['frames30']
ph = [{'a': math.floor(p['s'] * 30), 'b': math.ceil(p['e'] * 30)} for p in P['phrases']]
wd = [{'t': re.sub(r"[^a-z0-9']", '', w['w'].lower()), 'a': math.floor(w['s'] * 30), 'b': math.ceil(w['e'] * 30)} for w in W]
open('web/timing.js', 'w').write(f"// generated by gen_timing.py from {P['source']}\nexport const TOTAL = {TOTAL};\nexport const PH = {json.dumps(ph)};\nexport const WORDS = {json.dumps(wd)};\n")
print('TOTAL', TOTAL, 'phrases', len(ph))
