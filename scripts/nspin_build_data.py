#!/usr/bin/env python3
"""public/nspin/timing.json (VO segments) -> src/NightmareSpin/data.ts (scenes, camera keys, caption chunks, labels), frames @30."""
import json, re
FPS = 30
T = json.load(open('public/nspin/timing.json'))
segs = [s for s in T['segs'] if s['text']]
f = lambda t: round(t * FPS)
VO_END = 62.0; HOLD = 2.0
syl = lambda w: max(1, len(re.findall(r'[aeiouy]+', re.sub(r'[^a-z]', '', w.lower()))))
BEAT_OF = {}
for b, (a, z) in enumerate([(0, 3), (4, 8), (9, 12), (13, 23), (24, 31), (32, 39)]):
    for i in range(a, z + 1): BEAT_OF[i] = b
GREEN = {'churel', 'pale-hari', 'churel?'}; CRIM = {'shikaar', 'khauf', 'ulte', 'rona', 'shikaar?'}
words = []
for s in T['segs']:
    if not s['text']: continue
    toks = s['text'].split(); tot = sum(syl(w) for w in toks); x = s['s']
    for w in toks:
        d = (s['e'] - s['s']) * syl(w) / tot
        clean = re.sub(r'[.,?!—:¡]', '', w).lower()
        words.append({'t': w, 'a': round(x, 3), 'b': round(x + d, 3), 'seg': s['i'], 'beat': BEAT_OF.get(s['i'], 3), 'hot': 'g' if clean in GREEN else ('r' if clean in CRIM else '')}); x += d
# caption chunks: same beat, small gap, <= 2 lines of <= 26 chars
chunks, cur = [], []
def flush():
    global cur
    if not cur: return
    lines, line = [], []
    for w in cur:
        if line and len(' '.join(x['t'] for x in line + [w])) > 26: lines.append(line); line = []
        line.append(w)
    lines.append(line)
    chunks.append({'a': cur[0]['a'], 'b': cur[-1]['b'], 'lines': [[{'t': w['t'], 'a': w['a'], 'hot': w['hot']} for w in ln] for ln in lines]}); cur = []
for w in words:
    if cur:
        gap = w['a'] - cur[-1]['b']; chars = len(' '.join(x['t'] for x in cur + [w]))
        if w['beat'] != cur[-1]['beat'] or gap > 0.45 or chars > 50 or cur[-1]['t'][-1] in '.?!' and chars > 24: flush()
    cur.append(w)
flush()
for i, c in enumerate(chunks):
    nxt = chunks[i + 1]['a'] if i + 1 < len(chunks) else VO_END + HOLD
    c['b'] = min(c['b'] + 0.4, nxt - 0.05)
S = [5.45, 13.785, 20.1, 43.12, 53.44, VO_END, VO_END + HOLD]
N = [('s1', 'nspin-s1-spin-lock.jpg'), ('s2', 'nspin-s2-riverbank.jpg'), ('s3', 'nspin-s3-lore.jpg'), ('s4', 'nspin-s4-confrontation.jpg'), ('s5', 'nspin-s5-twist.jpg'), ('s6', 'nspin-s5-twist.jpg'), ('s7', 'nspin-s6-final-hold.jpg')]
# camera keys: [seconds, scale, focus x%, focus y%]
CAM = {
    's1': [[0, 1.0, 50, 50], [5.45, 1.08, 50, 50]],
    's2': [[5.45, 1.0, 50, 60], [13.785, 1.35, 44, 72]],
    's3': [[13.785, 1.0, 50, 62], [20.1, 1.32, 36, 72]],
    's4': [[20.1, 1.0, 50, 60], [27.0, 1.12, 38, 66], [31.0, 1.22, 36, 70], [35.0, 1.9, 50, 40], [39.0, 1.7, 50, 40], [43.12, 2.0, 50, 36]],
    's5': [[43.12, 1.0, 50, 58], [44.8, 1.12, 50, 56], [45.95, 1.12, 50, 56], [46.6, 1.75, 50, 84], [47.95, 1.75, 50, 84], [50.0, 1.9, 50, 46], [53.44, 2.1, 50, 46]],
    's6': [[53.44, 1.9, 50, 46], [62.0, 1.0, 50, 50]],
    's7': [[62.0, 1.03, 50, 40], [64.0, 1.03, 50, 40]],
}
scenes = [{'id': N[i][0], 'still': N[i][1], 'a': f(S[i - 1] if i else 0), 'b': f(S[i]) if i < len(S) else 0} for i in range(len(N))]
scenes = [{'id': N[i][0], 'still': N[i][1], 'a': f(0 if i == 0 else S[i - 1]), 'b': f(S[i]), 'cam': [[f(k[0]), k[1], k[2], k[3]] for k in CAM[N[i][0]]]} for i in range(len(N))]
total = f(VO_END + HOLD)
labels = [{'t': 'RAKSHAK', 'sub': 'CHUREL', 'side': 'l', 'a': f(0.35)}, {'t': 'KHAUF', 'sub': 'LA LLORONA', 'side': 'r', 'a': f(1.75)}]
out = {'total': total, 'scenes': scenes, 'chunks': [{'a': f(c['a']), 'b': f(c['b']), 'lines': [[{'t': w['t'], 'a': f(w['a']), 'hot': w['hot']} for w in ln] for ln in c['lines']]} for c in chunks], 'labels': labels, 'topCaptionScenes': ['s5']}
open('src/NightmareSpin/data.ts', 'w').write('// generated by scripts/nspin_build_data.py from public/nspin/timing.json - do not edit by hand\nexport const NSPIN = ' + json.dumps(out, ensure_ascii=False, indent=1) + ' as const;\n')
print('total frames', total, 'chunks', len(chunks), 'scenes', len(scenes))
